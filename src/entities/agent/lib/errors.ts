/** Понятный текст ошибки агента по коду (с префиксом `AGENT_` или без). */
const MANIFEST_ERRORS: Record<string, { title: string; hint: string }> = {
  COMMAND_UNDECLARED: {
    title: "Команда не объявлена",
    hint: "Воркер не объявил эту команду в манифесте — агент её не передаёт. Выберите команду из списка.",
  },
  COMMAND_INVALID: {
    title: "Аргументы не подходят под схему",
    hint: "Аргументы не подходят под схему команды из манифеста воркера — команда не отправлена.",
  },
  CONFIG_INVALID: {
    title: "Значение не подходит под схему",
    hint: "Значение не подходит под схему ключа из манифеста воркера — новая версия не задана.",
  },
  EVENT_UNDECLARED: {
    title: "Тип события не объявлен",
    hint: "Воркер не объявил этот тип события в манифесте.",
  },
  UNKNOWN_COMMAND: {
    title: "Воркер не знает команду",
    hint: "Команда есть в манифесте, но воркер её не выполняет — ошибка в коде воркера.",
  },
  TIMEOUT: {
    title: "Срок вышел",
    hint: "Воркер не ответил за отведённый срок — агент отменил команду.",
  },
  EXPIRED: {
    title: "Команда устарела",
    hint: "Агент получил команду после её срока и не выполнял её.",
  },
};

/**
 * Ошибка по манифесту воркера или сроку команды: заголовок и пояснение;
 * другой код — `null`.
 */
export const agentErrorText = (
  code: string | null | undefined,
): { title: string; hint: string } | null =>
  code ? (MANIFEST_ERRORS[code.replace(/^AGENT_/, "")] ?? null) : null;
