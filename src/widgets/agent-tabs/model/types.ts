/**
 * Что можно делать с агентом на вкладках. Права считает страница: на странице
 * агента — права раздела агентов, на карточке узла — права узла.
 */
export interface IAgentTabsAccess {
  /** Перезапуск и обновление воркеров. */
  canManage: boolean;
  /** Запись и удаление настроек воркеров. */
  canConfig: boolean;
  /** Команды воркерам (вкладка «Команды»). */
  canCommand: boolean;
  /** Журнал агента и воркеров с узла. */
  canLogs: boolean;
}
